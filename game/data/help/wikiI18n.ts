export function translateGameWikiText(text: string, locale: GameLocale): string | null {
  if (locale === 'fr') return text
  const index = WIKI_INDEX.get(text)
  if (index == null) return null
  return WIKI_TRANSLATIONS[locale][index] ?? text
}
